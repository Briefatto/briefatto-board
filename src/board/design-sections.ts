import { quotedConstraints } from "./constraints.js";
import { generatedEnd, generatedStart, type GuideInputs } from "./design-validation.js";

const tableCell = (value: string) => value.replace(/\|/g, "\\|").replace(/\s*\r?\n\s*/g, " ");
const row = (...cells: string[]) => `| ${cells.map(tableCell).join(" | ")} |`;

export function withGeneratedDesign(prose: string, { brief, samples }: GuideInputs): string {
  const newline = prose.match(/\r?\n/)?.[0] ?? "\n";
  const brandFacts = [...new Set([...(brief.brandFacts ?? []), ...(brief.acceptedBrandFacts ?? [])].map(({ value }) => value))];
  const campaign = brief.campaignCopy ?? [];
  const lines = [
    generatedStart,
    "",
    "## Verified brief and sample values",
    "",
    "Generated by Board from the recorded sources and rendered samples.",
    ...(brief.brandFacts ? [
      "", "### Brand facts", ...quotedConstraints(brandFacts),
      "", "### Campaign copy", "",
      ...campaign.length ? [row("Role", "Copy", "Source"), row("---", "---", "---"), ...campaign.map(({ role, copy, source }) => row(role, copy, source))]
        : ["No literal campaign copy was recorded in the brief."],
    ] : []),
    ...(brief.brandFacts || brief.clientConstraints.length ? [
      "", "### Client musts and must-nots",
      ...brief.clientConstraints.length ? quotedConstraints(brief.clientConstraints.map(({ value }) => value))
        : ["", "No explicit client constraints were recorded."],
    ] : []),
    "", "### Computed styles by sample", "",
  ];
  for (const sample of samples) {
    const { source, width, height, colours, paintedColours, typography } = sample;
    lines.push(`#### ${source} (${width} × ${height})`, "");
    if (typography.length) {
      lines.push(row("Text role", "Font stack", "Size", "Weight and style", "Text colour"), row("---", "---", "---", "---", "---"));
      for (const style of typography) {
        lines.push(row(style.role, `\`font-family: ${style.fontFamily}\``, style.fontSize, `${style.fontWeight} ${style.fontStyle}`, `\`${style.colour}\``));
      }
      lines.push("");
    }
    if (colours.length) {
      lines.push(row("Paint role", "Computed colour"), row("---", "---"));
      for (const { kind, value } of paintedColours) lines.push(row(kind, `\`colour: ${value}\``));
      const painted = new Set(paintedColours.map(({ value }) => value));
      for (const value of colours) if (!painted.has(value)) lines.push(row("Other computed styles", `\`colour: ${value}\``));
      lines.push("");
    }
  }
  lines.push(generatedEnd);
  const block = lines.join(newline);
  const markers = [...prose.matchAll(/^<!-- briefatto-board:generated (?:begin|end) -->(?=\r?$)/gm)];
  if (!markers.length) return prose + (prose ? newline + newline : "") + block + newline;
  const [start, end] = markers;
  if (markers.length !== 2 || start[0] !== generatedStart || end[0] !== generatedEnd) {
    throw new Error("FAIL DESIGN.md\n  generated-block: Expected one matching pair of Board-generated markers.");
  }
  return prose.slice(0, start.index) + block + prose.slice(end.index + end[0].length);
}
